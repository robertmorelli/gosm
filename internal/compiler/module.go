// Package compiler translates decoded WebAssembly modules into Go source.
package compiler

import (
	"fmt"
	"go/format"
	"regexp"
	"sort"
	"strconv"
	"strings"

	"gosm/internal/wasm"
)

// Options control code generation.
type Options struct {
	Package     string // Go package name
	RuntimePath string // import path of the runtime package (default "gosm/rt")
	Source      string // source file name, for the header comment
	// StringConstModules lists the import modules whose immutable global
	// imports are string constants equal to their field name (JS string
	// builtins "importedStringConstants"; Dart uses ""). nil means the
	// default ["'"]; an empty non-nil slice disables the feature.
	StringConstModules []string
	NoBuiltins         bool // treat wasm:js-string etc. as ordinary host imports
	HostOnly           bool // emit only the Host interface
	NoFormat           bool // skip gofmt (debugging)
	// HostType, if set, is a concrete Go type (e.g. "*Imports") defined in the
	// generated package, used for the host instead of the Host interface so
	// host methods are called directly and can be inlined. NewDynamic is then
	// not generated.
	HostType string
}

type compiler struct {
	m    *wasm.Module
	opts Options

	keys  []string
	canon []int
	tinfo map[int]*typeInfo

	pkgNames map[string]bool
	members  map[string]bool
	imports  map[string]bool

	funcNames   []string
	hostNames   map[int]string // import index -> Host method name
	builtin     map[uint32]string
	strConst    map[uint32]string // global index -> string constant
	globalCell  []bool
	globalName  []string
	refFuncs    map[uint32]bool
	nconst      int
	extra       strings.Builder // helper methods (const exprs)
	exportFns   map[uint32]bool
	exportNames map[int]string
	fconsts     map[string]string
	recursive   []bool
}

// Compile generates Go source for module m.
func Compile(m *wasm.Module, opts Options) (src []byte, err error) {
	defer func() {
		if r := recover(); r != nil {
			err = fmt.Errorf("gosm: %v", r)
		}
	}()
	if opts.Package == "" {
		opts.Package = "wasmmod"
	}
	if opts.RuntimePath == "" {
		opts.RuntimePath = "gosm/rt"
	}
	c := &compiler{
		m: m, opts: opts,
		pkgNames: map[string]bool{},
		members:  map[string]bool{},
		imports:  map[string]bool{},
		fconsts:  map[string]string{},
	}
	for _, n := range []string{"Instance", "Host", "New", "NewDynamic", "rt", "math", "bits", "unsafe", "dynHost", "funcRefHost"} {
		c.pkgNames[n] = true
	}
	c.computeTypes()
	c.assignNames()
	c.computeRecursive()
	var out strings.Builder
	if opts.HostOnly {
		c.writeHost(&out)
		hdr := fmt.Sprintf("// Host interface generated by gosm. DO NOT EDIT.\n\npackage %s\n\nimport rt %q\n\nvar _ rt.V128\n\n", opts.Package, opts.RuntimePath)
		return c.format(hdr + out.String())
	}
	c.writeTypes(&out)
	c.writeHost(&out)
	c.writeInstance(&out)
	c.writeFuncs(&out)
	out.WriteString(c.extra.String())
	if c.opts.HostType == "" {
		c.writeDynamic(&out)
	} else {
		fmt.Fprintf(&out, "var _ Host = (%s)(nil)\n", c.opts.HostType)
	}

	srcName := opts.Source
	if srcName == "" {
		srcName = "a WebAssembly module"
	}
	var hdr strings.Builder
	fmt.Fprintf(&hdr, "// Code generated by gosm from %s. DO NOT EDIT.\n\n", srcName)
	fmt.Fprintf(&hdr, "package %s\n\nimport (\n\t\"math\"\n\t\"math/bits\"\n\t\"unsafe\"\n\n\trt %q\n)\n\n", opts.Package, opts.RuntimePath)
	hdr.WriteString("var (\n\t_ = math.Abs\n\t_ = bits.Len\n\t_ unsafe.Pointer\n)\n\n")
	return c.format(hdr.String() + out.String())
}

func (c *compiler) format(s string) ([]byte, error) {
	if c.opts.NoFormat {
		return []byte(s), nil
	}
	b, err := format.Source([]byte(s))
	if err != nil {
		return []byte(s), fmt.Errorf("gosm: generated code does not parse: %v", err)
	}
	return b, nil
}

func (c *compiler) useImport(p string) { c.imports[p] = true }

func (c *compiler) hostType() string {
	if c.opts.HostType != "" {
		return c.opts.HostType
	}
	return "Host"
}

// --- naming ---

var slotLike = regexp.MustCompile(`^((s|c|x|ret|p|l|tc)\d+(_\d+)?|top)$`)

func (c *compiler) assignNames() {
	m := c.m
	c.hostNames = map[int]string{}
	c.builtin = map[uint32]string{}
	c.strConst = map[uint32]string{}
	c.refFuncs = map[uint32]bool{}
	c.exportFns = map[uint32]bool{}
	for _, n := range []string{"host", "funcs", "init", "Exports", "jsCache"} {
		c.members[n] = true
	}
	// host method names
	hostUsed := map[string]bool{}
	fi, gi := uint32(0), uint32(0)
	for i, im := range m.Imports {
		switch im.Kind {
		case wasm.ExtFunc:
			if b := c.builtinFor(im); b != "" {
				c.builtin[fi] = b
				fi++
				continue
			}
			fi++
		case wasm.ExtGlobal:
			if c.isStringConstModule(im.Module) && !im.Global.Mutable {
				c.strConst[gi] = im.Name
				gi++
				continue
			}
			gi++
		}
		base := hostMethodName(im.Module, im.Name)
		name := base
		for k := 2; hostUsed[name]; k++ {
			name = fmt.Sprintf("%s_%d", base, k)
		}
		hostUsed[name] = true
		c.hostNames[i] = name
	}
	// globals: cells for imported/exported
	c.globalCell = make([]bool, m.NumGlobals())
	c.globalName = make([]string, m.NumGlobals())
	for i := 0; i < m.NumImportedGlobals; i++ {
		c.globalCell[i] = true
	}
	for _, e := range m.Exports {
		switch e.Kind {
		case wasm.ExtGlobal:
			c.globalCell[e.Index] = true
		case wasm.ExtFunc:
			c.refFuncs[e.Index] = true
			c.exportFns[e.Index] = true
		}
	}
	for i := range c.globalName {
		c.globalName[i] = c.memberIdent(fmt.Sprintf("g%d", i))
	}
	for i := 0; i < m.NumMems(); i++ {
		c.memberIdent(fmt.Sprintf("mem%d", i))
	}
	for i := 0; i < m.NumTables(); i++ {
		c.memberIdent(fmt.Sprintf("tab%d", i))
	}
	for i := 0; i < m.NumTags(); i++ {
		c.memberIdent(fmt.Sprintf("tag%d", i))
	}
	for i := range m.Datas {
		c.memberIdent(fmt.Sprintf("data%d", i))
	}
	for i := range m.Elems {
		c.memberIdent(fmt.Sprintf("elem%d", i))
	}
	// referenced functions
	scan := func(code []wasm.Instr) {
		for _, in := range code {
			if in.Op == wasm.OpRefFunc {
				c.refFuncs[in.A] = true
			}
		}
	}
	for _, cd := range m.Codes {
		scan(cd.Body)
	}
	for _, g := range m.Globals {
		scan(g.Init)
	}
	for _, t := range m.Tables {
		scan(t.Init)
	}
	for _, e := range m.Elems {
		for _, x := range e.Inits {
			scan(x)
		}
	}
	// exported method names come first so they keep their natural names
	c.exportNames = map[int]string{}
	for i, e := range m.Exports {
		c.exportNames[i] = c.memberIdent(exportIdent(e.Name))
	}
	c.funcNames = make([]string, m.NumFuncs())
	exportName := map[uint32]string{}
	for _, e := range m.Exports {
		if e.Kind == wasm.ExtFunc {
			if _, ok := exportName[e.Index]; !ok {
				exportName[e.Index] = e.Name
			}
		}
	}
	for i := range c.funcNames {
		base := fmt.Sprintf("f%d", i)
		n, ok := m.Names.Funcs[uint32(i)]
		if !ok || n == "" {
			n, ok = exportName[uint32(i)]
		}
		if ok && n != "" {
			base = localIdent(n)
			if slotLike.MatchString(base) || base == "new" {
				base = "f_" + base
			}
		}
		c.funcNames[i] = c.memberIdent(base)
	}
}

func (c *compiler) isStringConstModule(mod string) bool {
	mods := c.opts.StringConstModules
	if mods == nil {
		mods = []string{"'"}
	}
	for _, m := range mods {
		if m == mod {
			return true
		}
	}
	return false
}

func (c *compiler) builtinFor(im wasm.Import) string {
	if c.opts.NoBuiltins {
		return ""
	}
	switch im.Module {
	case "wasm:js-string":
		if _, ok := jsStringBuiltins[im.Name]; ok {
			return im.Name
		}
	case "wasm:text-decoder":
		if im.Name == "decodeStringFromUTF8Array" {
			return im.Name
		}
	case "wasm:text-encoder":
		switch im.Name {
		case "measureStringAsUTF8", "encodeStringIntoUTF8Array", "encodeStringToUTF8Array":
			return im.Name
		}
	}
	return ""
}

func (c *compiler) funcName(fi uint32) string { return c.funcNames[fi] }

func (c *compiler) globalRef(gi uint32) string {
	if c.globalCell[gi] {
		return "m." + c.globalName[gi] + ".V"
	}
	return "m." + c.globalName[gi]
}

func (c *compiler) memRef(i uint32) string   { return fmt.Sprintf("m.mem%d", i) }
func (c *compiler) tableRef(i uint32) string { return fmt.Sprintf("m.tab%d", i) }
func (c *compiler) tagRef(i uint32) string   { return fmt.Sprintf("m.tag%d", i) }
func (c *compiler) dataRef(i uint32) string  { return fmt.Sprintf("m.data%d", i) }
func (c *compiler) elemRef(i uint32) string  { return fmt.Sprintf("m.elem%d", i) }
func (c *compiler) funcRefExpr(i uint32) string {
	c.refFuncs[i] = true
	return fmt.Sprintf("m.funcs[%d]", i)
}

func (c *compiler) ctorName(ti *typeInfo) string        { return "New" + ti.goName }
func (c *compiler) ctorDefaultName(ti *typeInfo) string { return "new" + ti.goName + "Default" }

// --- types ---

func (c *compiler) sortedTypes() []*typeInfo {
	var ts []*typeInfo
	for _, ti := range c.tinfo {
		ts = append(ts, ti)
	}
	sort.Slice(ts, func(i, j int) bool { return ts[i].idx < ts[j].idx })
	return ts
}

func (c *compiler) writeTypes(w *strings.Builder) {
	for _, ti := range c.sortedTypes() {
		st := &c.m.Types[ti.idx]
		switch ti.kind {
		case wasm.KindFunc:
			sup := "nil"
			if ti.super >= 0 {
				sup = c.tinfo[ti.super].rtt
			}
			fmt.Fprintf(w, "var %s = rt.CanonRTT(rt.KFunc, %s, %v, %q)\n\n", ti.rtt, sup, st.Final, c.keys[ti.idx])
			continue
		}
		kind := "rt.KStruct"
		if ti.kind == wasm.KindArray {
			kind = "rt.KArray"
		}
		sup := "nil"
		if ti.super >= 0 {
			sup = c.tinfo[ti.super].rtt
		}
		box := "nil"
		if ti.header {
			box = fmt.Sprintf("func(p unsafe.Pointer) any { return (*%s)(p) }", ti.goName)
			c.useImport("unsafe")
		}
		fmt.Fprintf(w, "var %s = rt.NewRTT(%s, %s, %v, %q, %s)\n\n", ti.rtt, kind, sup, st.Final, c.keys[ti.idx], box)

		// struct declaration
		if ti.kind == wasm.KindStruct {
			fmt.Fprintf(w, "// %s is the wasm struct type %s.\n", ti.goName, c.typeDesc(ti.idx))
		} else {
			fmt.Fprintf(w, "// %s is the wasm array type %s.\n", ti.goName, c.typeDesc(ti.idx))
		}
		fmt.Fprintf(w, "type %s struct {\n", ti.goName)
		ninh := 0
		if ti.super >= 0 {
			sup := c.tinfo[ti.super]
			fmt.Fprintf(w, "\t%s\n", sup.goName)
			ninh = len(sup.fields)
		} else if ti.header {
			w.WriteString("\trt.Object\n")
		}
		for _, fi := range ti.fields[ninh:] {
			if ti.kind == wasm.KindArray {
				fmt.Fprintf(w, "\tElems []%s\n", fi.storage)
			} else {
				fmt.Fprintf(w, "\t%s %s\n", fi.name, fi.storage)
			}
		}
		w.WriteString("}\n\n")
		if !ti.header {
			fmt.Fprintf(w, "func (*%s) WasmType() *rt.RTT { return %s }\n\n", ti.goName, ti.rtt)
		}
		if ti.kind == wasm.KindArray && ti.super < 0 {
			fmt.Fprintf(w, "func (a *%s) WasmLen() int { return len(a.Elems) }\n\n", ti.goName)
		}
		// constructors
		if ti.kind == wasm.KindStruct {
			var ps []string
			pn := ctorParamNames(ti)
			for i, fi := range ti.fields {
				ps = append(ps, fmt.Sprintf("%s %s", pn[i], fi.storage))
			}
			fmt.Fprintf(w, "// %s allocates a %s.\n", c.ctorName(ti), ti.goName)
			fmt.Fprintf(w, "func %s(%s) *%s {\n", c.ctorName(ti), strings.Join(ps, ", "), ti.goName)
			fmt.Fprintf(w, "\tp := &%s{}\n", ti.goName)
			if ti.header {
				fmt.Fprintf(w, "\tp.RTT = %s\n", ti.rtt)
			}
			for i, fi := range ti.fields {
				fmt.Fprintf(w, "\tp.%s = %s\n", fi.name, pn[i])
			}
			w.WriteString("\treturn p\n}\n\n")
			fmt.Fprintf(w, "func %s() *%s {\n", c.ctorDefaultName(ti), ti.goName)
			fmt.Fprintf(w, "\tp := &%s{}\n", ti.goName)
			if ti.header {
				fmt.Fprintf(w, "\tp.RTT = %s\n", ti.rtt)
			}
			w.WriteString("\treturn p\n}\n\n")
		} else {
			fi := ti.fields[0]
			fmt.Fprintf(w, "// %s allocates a %s holding elems.\n", c.ctorName(ti), ti.goName)
			fmt.Fprintf(w, "func %s(elems []%s) *%s {\n", c.ctorName(ti), fi.storage, ti.goName)
			fmt.Fprintf(w, "\tp := &%s{}\n", ti.goName)
			if ti.header {
				fmt.Fprintf(w, "\tp.RTT = %s\n", ti.rtt)
			}
			w.WriteString("\tp.Elems = elems\n\treturn p\n}\n\n")
		}
	}
}

func (c *compiler) typeDesc(idx int) string {
	st := &c.m.Types[idx]
	var b strings.Builder
	field := func(i int, f wasm.FieldType) {
		t := f.Type.String()
		if f.Mutable {
			t = "(mut " + t + ")"
		}
		if st.Comp.Kind == wasm.KindStruct {
			if n, ok := c.m.Names.Fields[uint32(idx)][uint32(i)]; ok {
				fmt.Fprintf(&b, " (field $%s %s)", n, t)
				return
			}
			fmt.Fprintf(&b, " (field %s)", t)
			return
		}
		b.WriteString(" " + t)
	}
	if st.Comp.Kind == wasm.KindStruct {
		b.WriteString("(struct")
	} else {
		b.WriteString("(array")
	}
	for i, f := range st.Comp.Fields {
		if b.Len() > 160 {
			b.WriteString(" ...")
			break
		}
		field(i, f)
	}
	b.WriteString(")")
	s := b.String()
	if len(st.Supers) > 0 {
		sup := c.tinfo[c.canon[st.Supers[0]]].goName
		s = fmt.Sprintf("(sub %s %s), a subtype of %s", sup, s, sup)
	} else if !st.Final {
		s = "(sub " + s + ")"
	}
	return s
}

func ctorParamNames(ti *typeInfo) []string {
	used := map[string]bool{}
	var out []string
	for i, fi := range ti.fields {
		n := localIdent(fi.name)
		if reservedLocals[n] || n == "p" || slotLike.MatchString(n) {
			n = fmt.Sprintf("f%d", i)
		}
		for used[n] {
			n += "_"
		}
		used[n] = true
		out = append(out, n)
	}
	return out
}

// --- Host interface ---

func (c *compiler) sigGo(ft *wasm.FuncType, names []string, withDepth bool) string {
	var ps []string
	if withDepth {
		ps = append(ps, "d int")
	}
	for i, p := range ft.Params {
		n := fmt.Sprintf("p%d", i)
		if names != nil && i < len(names) {
			n = names[i]
		}
		ps = append(ps, n+" "+c.goType(p))
	}
	s := "(" + strings.Join(ps, ", ") + ")"
	var rs []string
	for _, r := range ft.Results {
		rs = append(rs, c.goType(r))
	}
	switch len(rs) {
	case 0:
	case 1:
		s += " " + rs[0]
	default:
		s += " (" + strings.Join(rs, ", ") + ")"
	}
	return s
}

func (c *compiler) tableGo(tt wasm.TableType) string {
	return fmt.Sprintf("*rt.Table[%s]", c.goType(tt.Elem))
}

func (c *compiler) writeHost(w *strings.Builder) {
	w.WriteString("// Host supplies the module's imports. Each method is named\n// M_<module>_<field> (non-identifier bytes escaped as _hh).\n")
	w.WriteString("type Host interface {\n")
	for i, im := range c.m.Imports {
		name, ok := c.hostNames[i]
		if !ok {
			continue
		}
		fmt.Fprintf(w, "\t// %s imports %q %q.\n", name, im.Module, im.Name)
		switch im.Kind {
		case wasm.ExtFunc:
			fmt.Fprintf(w, "\t%s%s\n", name, c.sigGo(&c.m.Types[im.TypeIdx].Comp.Func, nil, false))
		case wasm.ExtMem:
			fmt.Fprintf(w, "\t%s() *rt.Memory\n", name)
		case wasm.ExtTable:
			fmt.Fprintf(w, "\t%s() %s\n", name, c.tableGo(im.Table))
		case wasm.ExtGlobal:
			fmt.Fprintf(w, "\t%s() *rt.Global[%s]\n", name, c.goType(im.Global.Type))
		case wasm.ExtTag:
			fmt.Fprintf(w, "\t%s() *rt.Tag\n", name)
		}
	}
	w.WriteString("}\n\n")
}

// --- Instance ---

func (c *compiler) writeInstance(w *strings.Builder) {
	m := c.m
	ht := c.hostType()
	fmt.Fprintf(w, "// Instance is an instantiated module.\ntype Instance struct {\n\thost %s\n\tfuncs []*rt.Func\n", ht)
	for i := 0; i < m.NumMems(); i++ {
		fmt.Fprintf(w, "\tmem%d *rt.Memory\n", i)
	}
	for i := 0; i < m.NumTables(); i++ {
		fmt.Fprintf(w, "\ttab%d %s\n", i, c.tableGo(m.TableType(uint32(i))))
	}
	for i := 0; i < m.NumGlobals(); i++ {
		gt := m.GlobalType(uint32(i))
		if c.globalCell[i] {
			fmt.Fprintf(w, "\t%s *rt.Global[%s]\n", c.globalName[i], c.goType(gt.Type))
		} else {
			fmt.Fprintf(w, "\t%s %s\n", c.globalName[i], c.goType(gt.Type))
		}
	}
	for i := 0; i < m.NumTags(); i++ {
		fmt.Fprintf(w, "\ttag%d *rt.Tag\n", i)
	}
	if len(c.builtin) > 0 {
		w.WriteString("\tjsCache rt.JSCache\n")
	}
	for i := range m.Datas {
		fmt.Fprintf(w, "\tdata%d []byte\n", i)
	}
	for i, e := range m.Elems {
		fmt.Fprintf(w, "\telem%d []%s\n", i, c.goType(e.Type))
	}
	w.WriteString("}\n\n")

	w.WriteString("// New instantiates the module. host may be nil if the module has no imports.\n")
	fmt.Fprintf(w, "func New(host %s) (*Instance, error) {\n", ht)
	w.WriteString("\tm := &Instance{host: host}\n\tif err := rt.Catch(m.init); err != nil {\n\t\treturn nil, err\n\t}\n\treturn m, nil\n}\n\n")

	// data segment contents
	for i, d := range m.Datas {
		fmt.Fprintf(w, "const dataSeg%d = %s\n\n", i, quoteBytes(d.Bytes))
	}

	var b strings.Builder
	b.WriteString("func (m *Instance) init() {\n")
	fmt.Fprintf(&b, "m.funcs = make([]*rt.Func, %d)\n", m.NumFuncs())
	// imports
	fi, mi, ti, gi, tgi := uint32(0), uint32(0), uint32(0), uint32(0), uint32(0)
	for i, im := range m.Imports {
		hn := c.hostNames[i]
		switch im.Kind {
		case wasm.ExtFunc:
			if c.refFuncs[fi] {
				ft := &m.Types[im.TypeIdx].Comp.Func
				fmt.Fprintf(&b, "m.funcs[%d] = &rt.Func{Type: %s, Fn: m.%s, Name: %q}\n", fi, c.info(im.TypeIdx).rtt, c.funcNames[fi], im.Module+"."+im.Name)
				_ = ft
				if hn != "" {
					fmt.Fprintf(&b, "if fh, ok := any(m.host).(interface{ WasmFuncRef(int) *rt.Func }); ok {\nif f := fh.WasmFuncRef(%d); f != nil {\nm.funcs[%d] = f\n}\n}\n", fi, fi)
				}
			}
			fi++
		case wasm.ExtMem:
			fmt.Fprintf(&b, "m.mem%d = m.host.%s()\n", mi, hn)
			l := im.Mem.Limits
			fmt.Fprintf(&b, "rt.CheckMemoryImport(m.mem%d, %d, %d, %v, %v)\n", mi, l.Min, l.Max, l.HasMax, l.Is64)
			mi++
		case wasm.ExtTable:
			fmt.Fprintf(&b, "m.tab%d = m.host.%s()\n", ti, hn)
			l := im.Table.Limits
			fmt.Fprintf(&b, "rt.CheckTableImport(m.tab%d, %d, %d, %v, %v, %q)\n", ti, l.Min, l.Max, l.HasMax, l.Is64, c.valKey(im.Table.Elem))
			ti++
		case wasm.ExtGlobal:
			gt := im.Global
			if s, ok := c.strConst[gi]; ok {
				fmt.Fprintf(&b, "m.%s = &rt.Global[%s]{V: %s, Type: %q}\n", c.globalName[gi], c.goType(gt.Type), strconv.Quote(s), c.valKey(gt.Type))
			} else {
				fmt.Fprintf(&b, "m.%s = m.host.%s()\n", c.globalName[gi], hn)
				fmt.Fprintf(&b, "rt.CheckGlobalImport(m.%s, %v, %q)\n", c.globalName[gi], gt.Mutable, c.valKey(gt.Type))
			}
			gi++
		case wasm.ExtTag:
			fmt.Fprintf(&b, "m.tag%d = m.host.%s()\n", tgi, hn)
			fmt.Fprintf(&b, "rt.CheckTagImport(m.tag%d, %s)\n", tgi, c.info(im.TypeIdx).rtt)
			tgi++
		}
	}
	for i, t := range m.Tags {
		fmt.Fprintf(&b, "m.tag%d = &rt.Tag{Type: %s}\n", m.NumImportedTags+i, c.info(t).rtt)
	}
	for i, mt := range m.Mems {
		l := mt.Limits
		fmt.Fprintf(&b, "m.mem%d = rt.NewMemory(%d, %d, %v, %v)\n", m.NumImportedMems+i, l.Min, l.Max, l.HasMax, l.Is64)
	}
	for i := m.NumImportedFuncs; i < m.NumFuncs(); i++ {
		if c.refFuncs[uint32(i)] {
			name := ""
			if n, ok := m.Names.Funcs[uint32(i)]; ok {
				name = n
			}
			fmt.Fprintf(&b, "m.funcs[%d] = &rt.Func{Type: %s, Fn: m.%s, Name: %q%s}\n", i, c.info(m.FuncTypeIdx(uint32(i))).rtt, c.funcNames[i], name, c.funcViews(uint32(i)))
		}
	}
	for i, g := range m.Globals {
		gidx := m.NumImportedGlobals + i
		e := c.constExpr(g.Init, g.Type.Type)
		if c.globalCell[gidx] {
			fmt.Fprintf(&b, "m.%s = &rt.Global[%s]{V: %s, Mutable: %v, Type: %q}\n", c.globalName[gidx], c.goType(g.Type.Type), e, g.Type.Mutable, c.valKey(g.Type.Type))
		} else {
			fmt.Fprintf(&b, "m.%s = %s\n", c.globalName[gidx], e)
		}
	}
	for i, t := range m.Tables {
		idx := m.NumImportedTables + i
		init := c.nullOf(t.Type.Elem)
		if t.Init != nil {
			init = c.constExpr(t.Init, t.Type.Elem)
		}
		l := t.Type.Limits
		fmt.Fprintf(&b, "m.tab%d = rt.NewTable[%s](%d, %d, %v, %v, %q, %s)\n", idx, c.goType(t.Type.Elem), l.Min, l.Max, l.HasMax, l.Is64, c.valKey(t.Type.Elem), init)
	}
	for i, e := range m.Elems {
		if e.Mode == wasm.SegDeclarative {
			continue
		}
		var xs []string
		for _, x := range e.Inits {
			xs = append(xs, c.constExpr(x, e.Type))
		}
		fmt.Fprintf(&b, "m.elem%d = []%s{%s}\n", i, c.goType(e.Type), strings.Join(xs, ", "))
	}
	for i, d := range m.Datas {
		fmt.Fprintf(&b, "m.data%d = []byte(dataSeg%d)\n", i, i)
		_ = d
	}
	for i, e := range m.Elems {
		if e.Mode != wasm.SegActive {
			continue
		}
		tt := m.TableType(e.Table)
		off := c.constExpr(e.Offset, offsetType(tt.Limits.Is64))
		seg := fmt.Sprintf("m.elem%d", i)
		if c.goType(e.Type) != c.goType(tt.Elem) {
			seg = fmt.Sprintf("rt.ConvSlice(%s, func(x %s) %s { return %s })", seg, c.goType(e.Type), c.goType(tt.Elem), c.conv("x", e.Type, tt.Elem))
		}
		fmt.Fprintf(&b, "m.tab%d.Init(%s, %s, 0, %d)\n", e.Table, u64Of(off, tt.Limits.Is64), seg, len(e.Inits))
		fmt.Fprintf(&b, "m.elem%d = nil\n", i)
	}
	for i, d := range m.Datas {
		if d.Mode != wasm.SegActive {
			continue
		}
		mt := m.MemType(d.Mem)
		off := c.constExpr(d.Offset, offsetType(mt.Limits.Is64))
		fmt.Fprintf(&b, "m.mem%d.Init(%s, m.data%d, 0, %d)\n", d.Mem, u64Of(off, mt.Limits.Is64), i, len(d.Bytes))
		fmt.Fprintf(&b, "m.data%d = nil\n", i)
	}
	if m.Start != nil {
		fmt.Fprintf(&b, "m.%s(0)\n", c.funcNames[*m.Start])
	}
	b.WriteString("}\n\n")
	w.WriteString(b.String())

	// exports
	var ex strings.Builder
	ex.WriteString("// Exports returns the module's exports by name: *rt.Func, *rt.Memory,\n// *rt.Table[T], *rt.Global[T] or *rt.Tag.\n")
	ex.WriteString("func (m *Instance) Exports() map[string]any {\n\treturn map[string]any{\n")
	for i, e := range m.Exports {
		mname := c.exportNames[i]
		switch e.Kind {
		case wasm.ExtFunc:
			fmt.Fprintf(&ex, "\t\t%q: m.funcs[%d],\n", e.Name, e.Index)
			ft := m.FuncType(e.Index)
			names := c.paramNames(e.Index)
			var args []string
			for _, n := range names {
				args = append(args, n)
			}
			fmt.Fprintf(w, "// %s calls the exported function %q.\n", mname, e.Name)
			call := fmt.Sprintf("m.%s(%s)", c.funcNames[e.Index], strings.Join(append([]string{"0"}, args...), ", "))
			if len(ft.Results) > 0 {
				call = "return " + call
			}
			fmt.Fprintf(w, "func (m *Instance) %s%s {\n\t%s\n}\n\n", mname, c.sigGo(ft, names, false), call)
		case wasm.ExtMem:
			fmt.Fprintf(&ex, "\t\t%q: m.mem%d,\n", e.Name, e.Index)
			fmt.Fprintf(w, "// %s returns the exported memory %q.\nfunc (m *Instance) %s() *rt.Memory { return m.mem%d }\n\n", mname, e.Name, mname, e.Index)
		case wasm.ExtTable:
			fmt.Fprintf(&ex, "\t\t%q: m.tab%d,\n", e.Name, e.Index)
			fmt.Fprintf(w, "// %s returns the exported table %q.\nfunc (m *Instance) %s() %s { return m.tab%d }\n\n", mname, e.Name, mname, c.tableGo(m.TableType(e.Index)), e.Index)
		case wasm.ExtGlobal:
			fmt.Fprintf(&ex, "\t\t%q: m.%s,\n", e.Name, c.globalName[e.Index])
			fmt.Fprintf(w, "// %s returns the exported global %q.\nfunc (m *Instance) %s() *rt.Global[%s] { return m.%s }\n\n", mname, e.Name, mname, c.goType(m.GlobalType(e.Index).Type), c.globalName[e.Index])
		case wasm.ExtTag:
			fmt.Fprintf(&ex, "\t\t%q: m.tag%d,\n", e.Name, e.Index)
			fmt.Fprintf(w, "// %s returns the exported tag %q.\nfunc (m *Instance) %s() *rt.Tag { return m.tag%d }\n\n", mname, e.Name, mname, e.Index)
		}
	}
	ex.WriteString("\t}\n}\n\n")
	w.WriteString(ex.String())
}

func offsetType(is64 bool) wasm.ValType {
	if is64 {
		return wasm.TI64
	}
	return wasm.TI32
}

func u64Of(e string, is64 bool) string {
	if is64 {
		return "rt.U64(" + e + ")"
	}
	return "rt.U32(" + e + ")"
}

func quoteBytes(b []byte) string {
	var s strings.Builder
	s.WriteByte('"')
	for _, c := range b {
		switch {
		case c == '"' || c == '\\':
			s.WriteByte('\\')
			s.WriteByte(c)
		case c >= 0x20 && c < 0x7F:
			s.WriteByte(c)
		default:
			fmt.Fprintf(&s, "\\x%02x", c)
		}
	}
	s.WriteByte('"')
	return s.String()
}

func (c *compiler) paramNames(fi uint32) []string {
	ft := c.m.FuncType(fi)
	used := map[string]bool{}
	var out []string
	for i := range ft.Params {
		n := fmt.Sprintf("p%d", i)
		if ln, ok := c.m.Names.Locals[fi][uint32(i)]; ok && ln != "" {
			n = localIdent(ln)
			if reservedLocals[n] || slotLike.MatchString(n) {
				n += "_"
			}
		}
		for used[n] {
			n += "_"
		}
		used[n] = true
		out = append(out, n)
	}
	return out
}

// constExpr compiles a constant expression to a Go expression (helper
// methods are generated for non-trivial expressions).
func (c *compiler) constExpr(code []wasm.Instr, t wasm.ValType) string {
	f := c.newFn(-1, nil, []wasm.ValType{t}, nil, nil)
	f.compileBody(code)
	body := f.w.String()
	if len(f.decls) == 0 && strings.HasPrefix(body, "return ") && strings.Count(body, "\n") == 1 {
		return strings.TrimSuffix(strings.TrimPrefix(body, "return "), "\n")
	}
	c.nconst++
	name := fmt.Sprintf("constExpr%d", c.nconst)
	c.members[name] = true
	hdr := fmt.Sprintf("func (m *Instance) %s() %s", name, c.goType(t))
	c.extra.WriteString(f.finish(hdr, body))
	return fmt.Sprintf("m.%s()", name)
}

// --- functions ---

func (c *compiler) newFn(idx int, params, results, locals []wasm.ValType, names []string) *fn {
	f := &fn{
		c: c, idx: idx, params: params, results: results,
		slots: map[slotKey]string{}, perH: map[int]int{},
		declType: map[string]string{}, read: map[string]bool{},
		w: &strings.Builder{}, startLabel: "top",
	}
	f.locals = append(append([]wasm.ValType{}, params...), locals...)
	f.lname = names
	return f
}

func (c *compiler) localNames(fi uint32, n int) []string {
	np := len(c.m.FuncType(fi).Params)
	names := c.paramNames(fi)
	used := map[string]bool{}
	for _, x := range names {
		used[x] = true
	}
	for i := np; i < n; i++ {
		x := fmt.Sprintf("l%d", i)
		if ln, ok := c.m.Names.Locals[fi][uint32(i)]; ok && ln != "" {
			x = localIdent(ln)
			if reservedLocals[x] || slotLike.MatchString(x) {
				x += "_"
			}
		}
		for used[x] {
			x += "_"
		}
		used[x] = true
		names = append(names, x)
	}
	return names
}

func (c *compiler) writeFuncs(w *strings.Builder) {
	m := c.m
	// imported function wrappers
	fi := uint32(0)
	for i, im := range m.Imports {
		if im.Kind != wasm.ExtFunc {
			continue
		}
		ft := &m.Types[im.TypeIdx].Comp.Func
		var args []string
		for k := range ft.Params {
			args = append(args, fmt.Sprintf("p%d", k))
		}
		var body string
		if b, ok := c.builtin[fi]; ok {
			body = c.builtinBody(b, ft)
		} else {
			body = fmt.Sprintf("m.host.%s(%s)", c.hostNames[i], strings.Join(args, ", "))
			if len(ft.Results) > 0 {
				body = "return " + body
			}
		}
		fmt.Fprintf(w, "func (m *Instance) %s%s {\n\t%s\n}\n\n", c.funcNames[fi], c.sigGo(ft, nil, true), body)
		fi++
	}
	for i, code := range m.Codes {
		idx := uint32(m.NumImportedFuncs + i)
		ft := m.FuncType(idx)
		names := c.localNames(idx, len(ft.Params)+len(code.Locals))
		f := c.newFn(int(idx), ft.Params, ft.Results, code.Locals, names)
		f.name = c.funcNames[idx]
		for k := len(ft.Params); k < len(f.locals); k++ {
			f.declare(names[k], c.goType(f.locals[k]))
		}
		func() {
			defer func() {
				if r := recover(); r != nil {
					panic(fmt.Sprintf("function %d (%s): %v", idx, f.name, r))
				}
			}()
			f.compileBody(code.Body)
		}()
		hdr := fmt.Sprintf("func (m *Instance) %s%s", c.funcNames[idx], c.sigGo(ft, names[:len(ft.Params)], true))
		w.WriteString(f.finish(hdr, f.w.String()))
	}
}

// funcViews returns a ", Views: ..." clause adapting function fi to each
// supertype of its type whose Go signature differs.
func (c *compiler) funcViews(fi uint32) string {
	tidx := c.m.FuncTypeIdx(fi)
	ft := c.m.FuncType(fi)
	own := c.goFuncSig(ft)
	var views []string
	for s := c.info(tidx).super; s >= 0; s = c.tinfo[s].super {
		st := &c.m.Types[s].Comp.Func
		sig := c.goFuncSig(st)
		if sig == own {
			continue
		}
		var ps, args, rs []string
		ps = append(ps, "d int")
		args = append(args, "d")
		for i, p := range st.Params {
			ps = append(ps, fmt.Sprintf("p%d %s", i, c.goType(p)))
			args = append(args, c.conv(fmt.Sprintf("p%d", i), p, ft.Params[i]))
		}
		call := fmt.Sprintf("m.%s(%s)", c.funcNames[fi], strings.Join(args, ", "))
		var body string
		switch len(st.Results) {
		case 0:
			body = call
		default:
			var outs, rets []string
			for i, r := range st.Results {
				outs = append(outs, fmt.Sprintf("r%d", i))
				rets = append(rets, c.conv(fmt.Sprintf("r%d", i), ft.Results[i], r))
				rs = append(rs, c.goType(r))
			}
			body = fmt.Sprintf("%s := %s\nreturn %s", strings.Join(outs, ", "), call, strings.Join(rets, ", "))
		}
		res := ""
		if len(rs) == 1 {
			res = " " + rs[0]
		} else if len(rs) > 1 {
			res = " (" + strings.Join(rs, ", ") + ")"
		}
		views = append(views, fmt.Sprintf("{Type: %s, Fn: func(%s)%s {\n%s\n}}", c.tinfo[s].rtt, strings.Join(ps, ", "), res, body))
	}
	if len(views) == 0 {
		return ""
	}
	return ", Views: []rt.FuncView{" + strings.Join(views, ", ") + "}"
}
